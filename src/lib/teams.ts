export function getTeamByName(nameOrId?: string | null): BrazilianTeam | undefined {
  if (!nameOrId) return undefined;
  const clean = nameOrId.toLowerCase().trim();
  return BRAZILIAN_TEAMS.find(
    (t) =>
      t.id === clean ||
      t.name.toLowerCase() === clean ||
      t.shortName.toLowerCase() === clean ||
      clean.includes(t.name.toLowerCase()) ||
      t.name.toLowerCase().includes(clean)
  );
}
